_VARIANT_MAP: dict[str, str] = {}
_VARIANT_GROUP_MAP: dict[str, tuple[str, ...]] = {}
for _group in _VARIANT_GROUPS:
    _canonical = _group[0]
    for _char in _group:
        _VARIANT_MAP.setdefault(_char, _canonical)
        _VARIANT_GROUP_MAP[_char] = tuple(_group)


def variant_forms(value: object) -> tuple[str, ...]:
    """返回该字符所在等价组的全部写法；不在组内时返回自身。"""
    text = str(value or "")
    if len(text) != 1:
        return (text,)
    return _VARIANT_GROUP_MAP.get(text, (text,))


def fold_variants(value: object) -> str:
    """把常见日文汉字/简繁异体统一到同一字符。"""
    return "".join(
        _VARIANT_MAP.get(char, char)
        for char in str(value or "")
    )
